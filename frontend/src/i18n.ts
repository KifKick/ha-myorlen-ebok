export const LOCALES: Record<string, Partial<Record<StringKey, string>>> = { en, pl };

export const language = (hass?: HomeAssistant): string =>
  (hass?.locale?.language ?? hass?.language ?? "en").split("-")[0];

export const t = (hass: HomeAssistant | undefined, key: StringKey, vars?: Record<string, string | number>): string => {
  let text = LOCALES[language(hass)]?.[key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(vars ?? {})) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
};
